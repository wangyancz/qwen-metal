#!/usr/bin/env python3
"""Generate golden host-math reference values from the installed diffusers.

Run with the diffusers venv python:
  /Volumes/Work/diffusers/.venv/bin/python tests/gen_host_ref.py

Writes tests/host_ref.h with static arrays consumed by tests/test_host.c.
The schedule values come from the real FlowMatchEulerDiscreteScheduler
loaded with the model's own scheduler_config.json, so the C port is tested
against the authoritative implementation rather than a transcription.
"""
import json
import os
import sys

import numpy as np
import torch

from diffusers import FlowMatchEulerDiscreteScheduler

MODEL_DIR = "/Volumes/Work/models/Qwen-Image-2.1.models"
OUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "host_ref.h")

# (steps, image_seq_len) pairs mirroring real pipeline call shapes.
SCHEDULE_CASES = [(20, 4096), (8, 1024), (50, 4096), (4, 1024)]


def mu_for(seq_len, base_seq=256, max_seq=8192, base_shift=0.5, max_shift=0.9):
    m = (max_shift - base_shift) / (max_seq - base_seq)
    b = base_shift - m * base_seq
    return seq_len * m + b


def fliteral(value):
    text = f"{value:.9g}"
    if "." not in text and "e" not in text and "E" not in text:
        text += ".0"
    return text + "f"


def main():
    config = json.load(open(os.path.join(MODEL_DIR, "scheduler", "scheduler_config.json")))
    scheduler = FlowMatchEulerDiscreteScheduler.from_config(config)

    lines = []
    lines.append("/* Generated by tests/gen_host_ref.py - do not edit by hand. */")
    lines.append("#ifndef HOST_REF_H")
    lines.append("#define HOST_REF_H")
    lines.append("")
    lines.append("typedef struct { int steps; int seq_len; const float *sigmas; } host_ref_case;")
    lines.append("")

    cases = []
    for index, (steps, seq_len) in enumerate(SCHEDULE_CASES):
        sigmas = np.linspace(1.0, 1.0 / steps, steps)
        scheduler.set_timesteps(num_inference_steps=steps, sigmas=list(sigmas),
                                mu=mu_for(seq_len))
        values = scheduler.sigmas.numpy().astype(np.float32)
        assert len(values) == steps + 1
        name = f"host_ref_sigmas_{index}"
        cases.append((steps, seq_len, name))
        body = ", ".join(fliteral(v) for v in values)
        lines.append(f"static const float {name}[{steps + 1}] = {{{body}}};")
        lines.append("")

    case_rows = ", ".join(
        f"{{{steps}, {seq_len}, {name}}}" for steps, seq_len, name in cases
    )
    lines.append(f"static const host_ref_case host_ref_cases[{len(cases)}] = {{{case_rows}}};")
    lines.append(f"#define HOST_REF_CASE_COUNT {len(cases)}")
    lines.append("")

    # RoPE tables exactly as QwenImage21Rope builds them.
    theta = 10000.0
    axes = [16, 56, 56]
    pos = torch.arange(8192)
    neg = torch.arange(1024).flip(0) * -1 - 1

    def rope_params(index, dim):
        freqs = torch.outer(index, 1.0 / torch.pow(theta, torch.arange(0, dim, 2).float().div(dim)))
        return torch.polar(torch.ones_like(freqs), freqs)

    tables = [torch.cat([rope_params(pos, d), rope_params(neg, d)], dim=0) for d in axes]

    sampled_positions = [0, 1, 2, 7, 255, 1023, 4095, 8191, 8192, 8193, 8703, 9215]
    lines.append("typedef struct { int axis; int table_row; int pair; float cos; float sin; } host_ref_rope;")
    rows = []
    for axis, table in enumerate(axes_tables := tables):
        dim = axes[axis]
        max_pair = dim // 2
        pairs = sorted({0, 1, max_pair // 2, max_pair - 1})
        for row in sampled_positions:
            for pair in pairs:
                value = table[row][pair]
                rows.append(
                    f"{{{axis}, {row}, {pair}, {fliteral(value.real)}, {fliteral(value.imag)}}}"
                )
    lines.append(f"static const host_ref_rope host_ref_rope_samples[{len(rows)}] = {{")
    for i in range(0, len(rows), 4):
        lines.append("    " + ", ".join(rows[i:i + 4]) + ",")
    lines.append("};")
    lines.append(f"#define HOST_REF_ROPE_COUNT {len(rows)}")
    lines.append("")
    lines.append("#endif")
    lines.append("")

    with open(OUT_PATH, "w") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {OUT_PATH}")
    for steps, seq_len, name in cases:
        print(f"  case steps={steps} seq={seq_len}")
    print(f"  rope samples: {len(rows)}")


if __name__ == "__main__":
    sys.exit(main())
